-- =============================================================================
-- 0071_tipo_cambio_ventas.sql   (requiere 0070 ya aplicado)
-- Las ventas en dolares cuentan en los totales en pesos.
--   * Cada venta en USD guarda su tipo de cambio.
--   * Si la factura trae el tipo de cambio (PDF "Tipo de cambio: 18.2345" o el XML), se usa ese.
--   * Si no, se usa el tipo de cambio oficial del dia de la factura: el que publica el DOF ese dia
--     (FIX de Banxico del dia habil anterior). El portal lo baja solo de internet cada dia.
--   * Las ventas en USD que ya estan subidas se llenan solas en cuanto el portal baja los tipos de cambio.
-- Como aplicarlo: pega este archivo COMPLETO en SQL Editor y presiona Run.
-- =============================================================================
begin;

create table if not exists public.tipos_cambio (
  fecha date primary key,
  usd_mxn numeric(10, 4) not null check (usd_mxn between 5 and 60),
  fuente text not null default 'banxico' check (fuente in ('banxico', 'referencia', 'manual')),
  created_at timestamptz not null default now()
);
alter table public.tipos_cambio enable row level security;
create policy tipos_cambio_select on public.tipos_cambio for select to authenticated using (true);
grant select on public.tipos_cambio to authenticated;

alter table public.ventas
  add column if not exists tipo_cambio numeric(10, 4) check (tipo_cambio is null or tipo_cambio between 5 and 60),
  add column if not exists tipo_cambio_fuente text check (tipo_cambio_fuente is null or tipo_cambio_fuente in ('factura', 'banxico', 'referencia', 'manual'));

-- Tipo de cambio que aplica a una fecha (DOF de ese dia = FIX del dia habil anterior).
create or replace function public.tipo_cambio_para(p_fecha date) returns table (usd_mxn numeric, fuente text)
language sql stable security definer set search_path = public as $$
  select t.usd_mxn, t.fuente from public.tipos_cambio t
   where t.fecha < p_fecha and t.fecha >= p_fecha - 10
   order by t.fecha desc limit 1;
$$;
grant execute on function public.tipo_cambio_para(date) to authenticated;

-- Al guardar una venta: si es en USD y no trae tipo de cambio, se pone el del dia; si es en MXN, ninguno.
create or replace function public.ventas_tipo_cambio() returns trigger
language plpgsql security definer set search_path = public as $$
declare r record;
begin
  if new.moneda = 'USD' then
    if new.tipo_cambio is null or (TG_OP = 'UPDATE' and new.fecha is distinct from old.fecha and coalesce(new.tipo_cambio_fuente, '') <> 'factura') then
      select * into r from public.tipo_cambio_para(new.fecha::date);
      new.tipo_cambio := r.usd_mxn;
      new.tipo_cambio_fuente := case when r.usd_mxn is null then null else r.fuente end;
    elsif new.tipo_cambio_fuente is null then
      new.tipo_cambio_fuente := 'manual';
    end if;
  else
    new.tipo_cambio := null;
    new.tipo_cambio_fuente := null;
  end if;
  return new;
end $$;
drop trigger if exists ventas_tipo_cambio on public.ventas;
create trigger ventas_tipo_cambio before insert or update of moneda, fecha, tipo_cambio on public.ventas
  for each row execute function public.ventas_tipo_cambio();

-- El tipo de cambio que trae la factura (lo pone el portal justo despues de registrarla).
create or replace function public.venta_tipo_cambio_factura(p_venta uuid, p_tc numeric) returns void
language plpgsql security definer set search_path = public as $$
declare v public.ventas;
begin
  select * into v from public.ventas where id = p_venta;
  if v.id is null then raise exception 'Venta no encontrada'; end if;
  if not (v.vendedor_id = auth.uid() or public.is_sales_manager()) then raise exception 'No autorizado' using errcode = '42501'; end if;
  if v.moneda <> 'USD' then return; end if;
  if p_tc is null or p_tc < 5 or p_tc > 60 then raise exception 'Tipo de cambio invalido'; end if;
  update public.ventas set tipo_cambio = round(p_tc, 4), tipo_cambio_fuente = 'factura' where id = p_venta;
end $$;
revoke all on function public.venta_tipo_cambio_factura(uuid, numeric) from public, anon;
grant execute on function public.venta_tipo_cambio_factura(uuid, numeric) to authenticated;

-- Llena las ventas en USD que no tienen tipo de cambio (lo llama el portal al bajar los tipos de cambio).
create or replace function public.ventas_rellenar_tipo_cambio() returns integer
language plpgsql security definer set search_path = public as $$
declare n integer;
begin
  -- Al poner tipo_cambio en null, el trigger le asigna el del dia.
  update public.ventas v set tipo_cambio = null
   where v.moneda = 'USD' and v.tipo_cambio is null
     and exists (select 1 from public.tipo_cambio_para(v.fecha::date));
  get diagnostics n = row_count;
  return n;
end $$;
revoke all on function public.ventas_rellenar_tipo_cambio() from public, anon, authenticated;
grant execute on function public.ventas_rellenar_tipo_cambio() to service_role;

-- Desde cuando faltan tipos de cambio (para que el portal sepa que bajar).
create or replace function public.tipo_cambio_pendiente_desde() returns date
language sql stable security definer set search_path = public as $$
  select min(fecha::date) from public.ventas where moneda = 'USD' and tipo_cambio is null;
$$;
revoke all on function public.tipo_cambio_pendiente_desde() from public, anon, authenticated;
grant execute on function public.tipo_cambio_pendiente_desde() to service_role;

